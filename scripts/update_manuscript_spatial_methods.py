#!/usr/bin/env python3
"""Synchronise the main-manuscript spatial-method wording with the locked figures."""

from pathlib import Path

from docx import Document


ROOT = Path(__file__).resolve().parents[1]

OLD = (
    "For DoRothEA-hypoxia analyses, the four projected epithelial programmes were standardised within section and reduced to three pooled state PCs, explaining 84.1% of their variance. For Stress_AP1-hypoxia analyses, leave-one-programme-out PCs were constructed from Epithelial_core, AT2_like and Ciliated, with the first two PCs explaining 73.7% of the variance. Scores were residualised against log total counts, detected-gene counts and the corresponding state PCs. Spatial concordance was quantified with bivariate Moran's I using a six-neighbour array-coordinate graph. Null expectations were generated by permuting score labels within 10, 15, 20 or 30 array-coordinate blocks, with 1,000 permutations per block size and empirical P values calculated as (b+1)/(B+1). This was treated as a locally constrained exploratory null rather than a variogram-preserving spatial surrogate. As a gene-overlap sensitivity, all 272 genes in the union of the de-overlapped DoRothEA and Hallmark hypoxia sets were removed from each state programme before rescoring and rebuilding the PC basis."
)

NEW = (
    "For DoRothEA-hypoxia analyses, the four projected epithelial programmes were standardised within section and reduced to three pooled state PCs, explaining 84.1% of their variance. For Stress_AP1-hypoxia analyses, leave-one-programme-out PCs were constructed from Epithelial_core, AT2_like and Ciliated, with the first two PCs explaining 73.7% of the variance. Scores were residualised against log total counts, detected-gene counts and the corresponding state PCs. Spatial concordance was quantified with bivariate Moran's I using a six-neighbour array-coordinate graph. Figure 5d compared the raw DoRothEA BACH1-hypoxia score pair with a 20-by-20 locally constrained block null, holding the raw DoRothEA score fixed while permuting raw hypoxia labels within blocks. Supplementary Figure 5 applied the same procedure to the state-PC-residualised score pair at block sizes of 10, 15, 20 and 30 array coordinates. Each analysis used 1,000 permutations and empirical P values calculated as (b+1)/(B+1), with the corresponding 2.5th and 97.5th percentiles reported as permutation intervals. These were treated as locally constrained exploratory nulls rather than variogram-preserving spatial surrogates. As a gene-overlap sensitivity, all 272 genes in the union of the de-overlapped DoRothEA and Hallmark hypoxia sets were removed from each state programme before rescoring and rebuilding the PC basis."
)


def update(path: Path) -> None:
    document = Document(path)
    matches = [p for p in document.paragraphs if p.text.strip() == OLD]
    if len(matches) == 0:
        if any(p.text.strip() == NEW for p in document.paragraphs):
            return
        raise RuntimeError(f"Could not locate the spatial-method paragraph in {path}")
    if len(matches) != 1:
        raise RuntimeError(f"Expected one spatial-method paragraph in {path}, found {len(matches)}")
    matches[0].text = NEW
    document.save(path)


if __name__ == "__main__":
    update(ROOT / "manuscript.docx")
    update(ROOT / "outputs/submission_package/manuscript.docx")
